#!/usr/bin/env python3
"""W8-14: bakes the hero "ULA" wordmark (the glass Y fills the first slot) into a single-channel SDF.

Usage (venv with fonttools, brotli, pillow, numpy, scipy):
  python3 scripts/build-wordmark-sdf.py

Reads the site's own Hanken Grotesk woff2 (scripts/fonts), lays "YULA" out exactly like the old 4096x2048
canvas (weight 600, em 340/1024 of the canvas width ... fitted to 92 percent), draws only "ULA", converts it to
a signed distance field and writes public/experience/yula-wordmark-sdf.bin (raw R8, 2560x1280, 0.5 = edge,
spread 20 texels) plus src/components/experience/wordmark-sdf-meta.ts (slot position). Run it again after
changing the font or layout constants.
"""
import io, os, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_WOFF2 = os.path.join(ROOT, "scripts/fonts/HankenGrotesk-latin-var.woff2")
OUT_BIN = os.path.join(ROOT, "public/experience/yula-wordmark-sdf.bin")
OUT_META = os.path.join(ROOT, "src/components/experience/wordmark-sdf-meta.ts")

W, H = 2560, 1280          # texture size (2:1, same plane mapping as the old canvas)
SS = 4                      # supersample for the exact distance field
SPREAD = 20.0               # texels either side of the edge
WEIGHT = 600
FONT_PX = 340 / 1024        # font size as a fraction of the texture width (old canvas: 340 of 1024)

tt = TTFont(FONT_WOFF2); tt.flavor = None
buf = io.BytesIO(); tt.save(buf); buf.seek(0)
hw, hh = W * SS, H * SS
size = round(FONT_PX * hw)
font = ImageFont.truetype(buf, size)
try:
    font.set_variation_by_axes([WEIGHT])
except Exception as e:
    sys.exit(f"variable axis failed: {e}")

label = "YULA"
full = font.getlength(label)
first = font.getlength(label[:1])
max_w = hw * 0.92
fit = min(1.0, max_w / full)
if fit < 1.0:  # canvas maxWidth squeezes the glyphs horizontally; mimic with a width scale
    pass
start = (hw - full * fit) / 2
centre_y = hh / 2 + 12 * (hw / 1024)
asc, desc = font.getmetrics()
baseline = centre_y + (asc - desc) / 2  # textBaseline "middle" = em box middle
# Keep the cap-height centre where the previous wordmark had it (heroSlot.y 0.02 of the plane height, above centre).
_u = font.getbbox("U", anchor="ls")
baseline -= (0.02 - (hh / 2 - (baseline + (_u[1] + _u[3]) / 2)) / hh) * hh

# draw "ULA" (unsqueezed, then scale x by fit) on a local strip
rest = label[1:]
rest_w = int(font.getlength(rest)) + 8
strip = Image.new("L", (rest_w, hh), 0)
ImageDraw.Draw(strip).text((0, baseline), rest, font=font, fill=255, anchor="ls")
if fit < 1.0:
    strip = strip.resize((max(1, round(rest_w * fit)), hh), Image.LANCZOS)
img = Image.new("L", (hw, hh), 0)
img.paste(strip, (round(start + first * fit), 0))
mask = np.asarray(img) >= 128

# cap metrics of "U" (relative to the same baseline)
u = font.getbbox("U", anchor="ls")  # (l, top, r, bottom) relative to baseline
cap_top, cap_bot = baseline + u[1], baseline + u[3]
slot_x = (start + first * fit / 2 - hw / 2) / hw
slot_cap = (cap_bot - cap_top) / hh
slot_y = (hh / 2 - (cap_top + cap_bot) / 2) / hh

inside = distance_transform_edt(mask)
outside = distance_transform_edt(~mask)
sd = (outside - inside).astype(np.float32)           # + outside, - inside (pixels)
sd = sd.reshape(H, SS, W, SS).mean(axis=(1, 3)) / SS  # texels
v = 0.5 - sd / (2 * SPREAD)                            # inside > 0.5
data = np.clip(np.round(v * 255), 0, 255).astype(np.uint8)
os.makedirs(os.path.dirname(OUT_BIN), exist_ok=True)
data.tofile(OUT_BIN)
meta = (
    "/* Generated by scripts/build-wordmark-sdf.py; do not edit. */\n"
    f"export const WORDMARK_SDF_SIZE = {{ width: {W}, height: {H} }} as const;\n"
    f"export const WORDMARK_SDF_SPREAD = {SPREAD};\n"
    f"export const WORDMARK_SLOT = {{ x: {slot_x:.5f}, y: {slot_y:.5f}, cap: {slot_cap:.5f} }} as const;\n"
)
open(OUT_META, "w").write(meta)
print(f"bytes={os.path.getsize(OUT_BIN)} slot x={slot_x:.4f} y={slot_y:.4f} cap={slot_cap:.4f} fit={fit:.3f}")
